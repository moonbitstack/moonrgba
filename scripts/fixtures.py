"""Turns a generated table into a MoonBit test fixture.

    python scripts/fixtures.py vectors vectors.tsv src/vectors_wbtest.mbt
    python scripts/fixtures.py wpt wpt.tsv src/wpt_wbtest.mbt
    python scripts/fixtures.py numbers numbers.tsv src/numbers_wbtest.mbt
    python scripts/fixtures.py deltas deltas.tsv src/deltas_wbtest.mbt

Each row becomes one string with its fields separated by tabs. Keeping the rows
as text rather than as typed tuples means a regenerated fixture shows up in a
diff as the values that changed rather than as a whole file.
"""

import sys

HEADERS = {
    "vectors": """\
// Generated by scripts/fixtures.py from scripts/vectors.mjs. Do not edit.
//
// Conversions between every pair the library can route through, computed by two
// references that share no code: the sample code CSS Color 4 ships, and
// colorjs.io. A row that disagrees with either is a bug in this library unless
// the test says otherwise.
""",
    "wpt": """\
// Generated by scripts/fixtures.py from scripts/wpt.mjs. Do not edit.
//
// The parsing cases of web-platform-tests' css/css-color/parsing, collected by
// running those test files' own scripts. Each row is `valid` or `invalid`, the
// value, and the serialisation the test expects where it states one.
""",
    "numbers": """\
// Generated by scripts/fixtures.py from scripts/numbers.mjs. Do not edit.
//
// Colour differences and contrast ratios computed by colorjs.io from seeded
// random pairs. Each row is the measure, the space, six components, the value.
""",
    "deltas": """\
// Generated by scripts/fixtures.py from scripts/deltas.py. Do not edit.
//
// Colour differences computed by colour-science: 76, 94 and 2000, over random
// pairs and over the set Sharma, Wu and Dalal publish for CIEDE2000.
""",
}

NAMES = {
    "vectors": "vectors",
    "wpt": "wpt_cases",
    "numbers": "numbers",
    "deltas": "deltas",
}


def main(kind: str, source: str, target: str) -> None:
    with open(source, encoding="utf-8") as handle:
        rows = [line.rstrip("\n") for line in handle if line.strip()]

    with open(target, "w", encoding="utf-8") as handle:
        handle.write(HEADERS[kind])
        handle.write("\n")
        handle.write("let %s : Array[String] = [\n" % NAMES[kind])
        for row in rows:
            handle.write('  "%s",\n' % row)
        handle.write("]\n")
    print(f"{len(rows)} rows written to {target}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
